/**
 * Regenerates src/infrastructure/cms/apple-certificates.ts from https://www.apple.com/certificateauthority/.
 *
 *   pnpm --filter @ipaforge/signer update-apple-certificates            # rewrite the file
 *   pnpm --filter @ipaforge/signer update-apple-certificates -- --check # exit 1 if Apple's set changed (CI, monthly)
 *
 * Trust rules: roots are trust anchors and are never accepted automatically. A root whose SHA-256
 * differs from the currently pinned set requires --allow-new-roots (and a human review of the diff).
 * Intermediates are accepted only if a pinned root verifiably signed them and they are valid CAs.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import * as pkijs from 'pkijs'

import { toBase64, toHex } from '@ipaforge/kernel'
import { APPLE_CERTIFICATES } from '@signer/infrastructure/cms/apple-certificates.ts'
import { parseCertificate } from '@signer/infrastructure/cms/certificate.ts'
import { OID_BASIC_CONSTRAINTS } from '@signer/infrastructure/cms/oids.ts'

const CA_PAGE = 'https://www.apple.com/certificateauthority/'
const ROOTS: readonly { name: string; url: string }[] = [
  {
    name: 'Apple Root CA',
    url: 'https://www.apple.com/appleca/AppleIncRootCertificate.cer'
  },
  {
    name: 'Apple Root CA - G3',
    url: 'https://www.apple.com/certificateauthority/AppleRootCA-G3.cer'
  }
]
const TARGET = join(
  import.meta.dirname,
  '../src/infrastructure/cms/apple-certificates.ts'
)

const check = process.argv.includes('--check')
const allowNewRoots = process.argv.includes('--allow-new-roots')
const log = (message: string): void =>
  console.info(`[apple-certificates] ${message}`)

const download = async (url: string): Promise<Uint8Array> => {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`)
  return new Uint8Array(await response.arrayBuffer())
}

const sha256 = async (bytes: Uint8Array): Promise<string> =>
  toHex(
    new Uint8Array(
      await crypto.subtle.digest('SHA-256', bytes as Uint8Array<ArrayBuffer>)
    )
  )

const isCa = (cert: pkijs.Certificate): boolean => {
  const value = cert.extensions?.find(
    (e) => e.extnID === OID_BASIC_CONSTRAINTS
  )?.parsedValue

  return value instanceof pkijs.BasicConstraints && value.cA === true
}

type Entry = {
  readonly name: string
  readonly kind: 'root' | 'intermediate'
  readonly sha256: string
  readonly expires: string
  readonly der: Uint8Array
}

const render = (entries: readonly Entry[]): string => {
  const lines = [
    `// Generated by packages/signer/scripts/update-apple-certificates.ts from ${CA_PAGE}`,
    '// Roots are pinned trust anchors (changes need --allow-new-roots and review); every intermediate was',
    '// verified to be a CA signed by a pinned root. Do not edit by hand.',
    '',
    'export interface AppleCertificate {',
    '  readonly name: string;',
    '  readonly kind: "root" | "intermediate";',
    '  readonly sha256: string;',
    '  readonly expires: string;',
    '  /** DER, base64. */',
    '  readonly der: string;',
    '}',
    '',
    'export const APPLE_CERTIFICATES: readonly AppleCertificate[] = ['
  ]
  for (const entry of entries) {
    const b64 = toBase64(entry.der)
    lines.push(
      '  {',
      `    name: "${entry.name}",`,
      `    kind: "${entry.kind}",`,
      `    sha256: "${entry.sha256}",`,
      `    expires: "${entry.expires}",`,
      '    der: [',
      ...Array.from(
        { length: Math.ceil(b64.length / 100) },
        (_, i) => `      "${b64.slice(i * 100, i * 100 + 100)}",`
      ),
      '    ].join(""),',
      '  },'
    )
  }
  lines.push('];', '')
  // format exactly like the repository's formatter would
  return execFileSync(
    'pnpm',
    ['exec', 'biome', 'format', `--stdin-file-path=${TARGET}`],
    {
      input: lines.join('\n'),
      encoding: 'utf8'
    }
  )
}

/** A certificate the trust rules refuse; the run stops with exit code 1. */
class Refused extends Error {}

/** Downloads the pinned roots; a root whose digest changed needs --allow-new-roots. */
const fetchRoots = async (): Promise<{
  readonly entries: Entry[]
  readonly certificates: pkijs.Certificate[]
}> => {
  const pinnedRoots = new Set(
    APPLE_CERTIFICATES.filter((c) => c.kind === 'root').map((c) => c.sha256)
  )
  const entries: Entry[] = []
  const certificates: pkijs.Certificate[] = []
  for (const root of ROOTS) {
    const der = await download(root.url)
    const digest = await sha256(der)
    if (!pinnedRoots.has(digest) && !allowNewRoots) {
      throw new Refused(
        `${root.name} changed (${digest}); review it and rerun with --allow-new-roots`
      )
    }
    const cert = parseCertificate(der)
    certificates.push(cert)
    entries.push({
      name: root.name,
      kind: 'root',
      sha256: digest,
      expires: cert.notAfter.value.toISOString(),
      der
    })
  }
  return { entries, certificates }
}

/** The WWDR intermediate generations Apple's CA page links to, ascending. */
const publishedGenerations = async (): Promise<number[]> => {
  const page = await (await fetch(CA_PAGE)).text()

  return [
    ...new Set(
      [...page.matchAll(/AppleWWDRCAG(\d+)\.cer/g)].map((m) => Number(m[1]))
    )
  ].sort((a, b) => a - b)
}

const isSignedByAny = async (
  cert: pkijs.Certificate,
  roots: readonly pkijs.Certificate[]
): Promise<boolean> =>
  (
    await Promise.all(roots.map((root) => cert.verify(root).catch(() => false)))
  ).some(Boolean)

/** WWDR generation `generation`, verified against `roots`; `undefined` when it has expired. */
const intermediateEntry = async (
  generation: number,
  roots: readonly pkijs.Certificate[]
): Promise<Entry | undefined> => {
  const der = await download(`${CA_PAGE}AppleWWDRCAG${generation}.cer`)
  const cert = parseCertificate(der)
  const signedByRoot = await isSignedByAny(cert, roots)
  if (!signedByRoot)
    throw new Refused(
      `WWDR G${generation} is not signed by a pinned root; refusing`
    )
  if (!isCa(cert))
    throw new Refused(`WWDR G${generation} is not a CA; refusing`)
  const expires = cert.notAfter.value
  if (expires.getTime() < Date.now()) {
    log(`- skipping WWDR G${generation}: expired ${expires.toISOString()}`)
    return undefined
  }
  return {
    name: `Apple WWDR CA G${generation}`,
    kind: 'intermediate',
    sha256: await sha256(der),
    expires: expires.toISOString(),
    der
  }
}

const generationName = (generation: number): string => `G${generation}`

const listOrNone = (names: readonly string[]): string =>
  names.join(', ') || 'none'

/** Names added, removed and changed between the bundled set and `entries`. */
const diff = (entries: readonly Entry[]) => {
  const before = new Map(APPLE_CERTIFICATES.map((c) => [c.name, c.sha256]))
  const after = new Map(entries.map((e) => [e.name, e.sha256]))

  return {
    added: [...after.keys()].filter((name) => !before.has(name)),
    removed: [...before.keys()].filter((name) => !after.has(name)),
    changed: [...after.keys()].filter(
      (name) => before.has(name) && before.get(name) !== after.get(name)
    )
  }
}

/** Writes `entries` to the bundled file, or (with --check) only reports whether it is out of date. */
const apply = (entries: readonly Entry[]): number => {
  const next = render(entries)
  const current = readFileSync(TARGET, 'utf8')
  const { added, removed, changed } = diff(entries)
  const contentChanged = added.length + removed.length + changed.length > 0

  if (!contentChanged) {
    if (!check && next !== current) writeFileSync(TARGET, next) // formatting-only refresh
    log("✓ bundled certificates match Apple's published set")
    return 0
  }
  log(
    `changes — added: ${listOrNone(added)}; removed: ${listOrNone(removed)}; changed: ${listOrNone(changed)}`
  )
  if (check) {
    log(
      '✗ out of date: run `pnpm --filter @ipaforge/signer update-apple-certificates`, review, and commit'
    )
    return 1
  }
  writeFileSync(TARGET, next)
  log(`✓ wrote ${TARGET}`)
  return 0
}

const update = async (): Promise<number> => {
  const roots = await fetchRoots()
  const generations = await publishedGenerations()
  log(
    `Apple publishes WWDR intermediates: ${generations.map(generationName).join(', ')}`
  )
  const entries = [...roots.entries]
  for (const generation of generations) {
    const entry = await intermediateEntry(generation, roots.certificates)
    if (entry) entries.push(entry)
  }
  return apply(entries)
}

const main = async (): Promise<number> => {
  try {
    return await update()
  } catch (error) {
    if (!(error instanceof Refused)) throw error
    log(`✗ ${error.message}`)
    return 1
  }
}

process.exitCode = await main()
